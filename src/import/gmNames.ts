/** "Cowbell" for 56, or null if General MIDI has no drum on that note. */
export function gmDrumName(note: number): string | null {
  return GM_DRUM_NAMES.get(note) ?? null;
}

/** "note 56 (Cowbell)", or "note 12" when General MIDI has no name for it. */
export function describeMidiNote(note: number): string {
  const name = gmDrumName(note);
  return name ? `note ${note} (${name})` : `note ${note}`;
}
